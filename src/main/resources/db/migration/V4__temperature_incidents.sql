ALTER TABLE temperature_alert_states
    ADD COLUMN consecutive_normal_readings INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT chk_temperature_normal_readings CHECK (consecutive_normal_readings BETWEEN 0 AND 3);

CREATE TABLE temperature_incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id VARCHAR(255) NOT NULL,
    opened_at TIMESTAMP(6) WITH TIME ZONE,
    acknowledged_at TIMESTAMP(6) WITH TIME ZONE,
    recovered_at TIMESTAMP(6) WITH TIME ZONE,
    threshold_at_open DOUBLE PRECISION,
    temperature_at_open DOUBLE PRECISION,
    migrated BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_incident_onset_known CHECK (
        migrated OR (opened_at IS NOT NULL AND threshold_at_open IS NOT NULL AND temperature_at_open IS NOT NULL))
);
CREATE UNIQUE INDEX uq_temperature_incident_active_sensor
    ON temperature_incidents (sensor_id) WHERE recovered_at IS NULL;
CREATE INDEX idx_temperature_incidents_sensor_id ON temperature_incidents (sensor_id, id DESC);

